package com.mahdi.lang

/**
 * اللغات المثبتة **مسبقًا** داخل التطبيق (4.0.0).
 *
 * ثلاثة مفسّرات تأتي جاهزة مع الصورة المدمجة، فلا يحتاج المستخدم إنترنت ولا انتظارًا
 * ليبدأ العمل بها: **Python** و**PHP** و**HTML**. هذه اللغات:
 * - تظهر دائمًا بشارة «مثبت مسبقًا» بلون مميّز،
 * - **لا يمكن حذفها** (لا يظهر لها زرّ X ولا تُقبل إزالتها من أي شاشة).
 *
 * ما عداها يُثبَّت من متجر الإضافات أو من شاشة اللغات، ويبقى قابلًا للحذف.
 */
object DefaultLanguages {

    /** معرّفات اللغات المدمجة (نفس معرّفات [LanguageRegistry]). */
    val bundled: Set<String> = setOf("python", "php", "html")

    /** هل اللغة مدمجة داخل التطبيق؟ */
    fun isBundled(id: String): Boolean = id in bundled

    /** هل يمكن حذف هذه اللغة؟ (كل ما ليس مدمجًا) */
    fun isRemovable(id: String): Boolean = !isBundled(id)
}
